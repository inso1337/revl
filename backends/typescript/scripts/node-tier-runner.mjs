// Run an emitted revl test module under PLAIN NODE — the runtime the ts tier
// ships on (issue #295).
//
//     node scripts/node-tier-runner.mjs <emitted .test.ts>
//
// `revl test --backend ts` executes the emitted module under **vitest**.
// `revl run --backend ts` and `revl run --placement` execute it under **plain
// node** (`src/revl/placement.py` builds `["node", placement_runner.ts, spec]`).
// Those are not the same environment, and the difference is not cosmetic —
// measured on this repo's own vitest 4.1.10 and node 26, vitest additionally
// supplies a CommonJS module scope (`require`, `module`, `exports`,
// `__dirname`, `__filename`), vite's module resolution (extensionless
// imports, `.js`->`.ts` remap, directory/index imports, attribute-less JSON
// imports) and full TypeScript (`enum`, `namespace`, parameter properties,
// `import x = require(...)`), all of which node refuses. The full measurement
// and the resulting contract are in docs/ts-runtime-contract.md.
//
// So a green vitest run said "this runs under vitest", not "this runs on the
// ts tier", and no gate could tell the two apart. This runner is the gate:
// the SAME generated bytes vitest just executed are executed again by node,
// with the specifier `vitest` resolved to `scripts/vitest-shim.mjs` (the two
// names `emit.py` emits, nothing more). Anything the module got from vitest
// rather than from the tier fails here.
//
// Exit code 0 = every `it()` passed. Nonzero = a failure, printed as
// `FAIL <name>: <message>`; a module that will not even load (node's
// `ERR_UNSUPPORTED_TYPESCRIPT_SYNTAX`, `ERR_MODULE_NOT_FOUND`,
// `require is not defined`) fails the same way, before any case runs.

import { registerHooks } from 'node:module'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const target = process.argv[2]
if (!target) {
  console.error('usage: node scripts/node-tier-runner.mjs <emitted .test.ts>')
  process.exit(2)
}

const shim = pathToFileURL(path.join(import.meta.dirname, 'vitest-shim.mjs')).href

// Synchronous resolve hook (node >= 22.15 / >= 23.5): no loader thread, no
// flags, and it applies to the module graph loaded below. Only the bare
// specifier `vitest` is intercepted — everything else, including
// `../../runtime.ts` and `cordis`, resolves exactly as it does for
// placement_runner.ts, which is the whole point.
registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier === 'vitest') return { url: shim, shortCircuit: true }
    return nextResolve(specifier, context)
  },
})

globalThis.__REVL_NODE_TIER__ = { cases: [] }

// Collect (module evaluation) and then run, the order vitest uses: an `it()`
// body must not run while the module is still evaluating.
await import(pathToFileURL(path.resolve(target)).href)

const { cases } = globalThis.__REVL_NODE_TIER__
let failed = 0
for (const testCase of cases) {
  try {
    await testCase.fn()
  } catch (error) {
    failed += 1
    const message = error && error.message ? error.message : String(error)
    console.error(`FAIL ${testCase.name}: ${message}`)
  }
}

if (failed > 0) {
  console.error(`node tier: ${failed} of ${cases.length} emitted test(s) failed under plain node`)
} else {
  console.log(`node tier: ${cases.length} emitted test(s) passed under plain node`)
}

// Exit explicitly rather than letting the loop drain. A `lifecycle test` boots
// a live cordis Context, and a runtime handle that outlives the teardown would
// hang this process until the caller's timeout — which reads as a tier failure
// and says nothing about the code. Flush both streams first: `process.exit`
// truncates a pipe mid-write, and the caller captures this output.
await Promise.all([
  new Promise((resolve) => process.stdout.write('', resolve)),
  new Promise((resolve) => process.stderr.write('', resolve)),
])
process.exit(failed > 0 ? 1 : 0)
