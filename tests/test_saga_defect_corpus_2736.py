# Each of these is a runner error, never a verdict (fix round of PR #3105).

def _compiled_stub(monkeypatch, failed, counts, problems):
    monkeypatch.setattr(R, "_compile", lambda _path: ({"components": []}, None))
    monkeypatch.setattr(R, "_sweep", lambda _ir, _component: (failed, counts, problems))
    return next(row for row in RUNTIME_ROWS if row["expected"] == "missed")


def test_a_sweep_of_zero_steps_is_a_runner_error_not_missed(monkeypatch):
    row = _compiled_stub(monkeypatch, 0, {"steps": 0, "failed": 0}, [])
    with pytest.raises(R.CorpusError, match="zero steps"):
        R.measure(row)


def test_a_one_step_sweep_that_passes_is_missed(monkeypatch):
    # control for the zero-step check: one passing step is a verdict
    row = _compiled_stub(monkeypatch, 0, {"steps": 1, "failed": 0}, [])
    assert R.measure(row)["verdict"] == "missed"


def test_a_crash_of_the_sweep_driver_is_a_runner_error_not_fault_test(monkeypatch):
    # the problem line is the one `revl.fault` itself writes for a driver crash
    fault = importlib.import_module("revl.fault")
    crash = fault._driver_failure(types.SimpleNamespace(), RuntimeError("boom"),
                                  "fault-test")
    row = _compiled_stub(monkeypatch, 1, {"steps": 3, "failed": 1}, [crash])
    with pytest.raises(R.CorpusError, match="sweep driver failed"):
        R.measure(row)


def test_an_emitter_refusal_in_the_sweep_is_a_runner_error(monkeypatch):
    fault = importlib.import_module("revl.fault")

    class EmitError(ValueError):
        pass

    refusal = fault._driver_failure(types.SimpleNamespace(EmitError=EmitError),
                                    EmitError("cannot lower"), "fault-test")
    row = _compiled_stub(monkeypatch, 1, {"steps": 3, "failed": 1}, [refusal])
    with pytest.raises(R.CorpusError, match="sweep driver failed"):
        R.measure(row)


def test_a_seeded_fault_failure_is_still_fault_test(monkeypatch):
    # control for the driver-crash check: a judged problem is a verdict
    row = _compiled_stub(monkeypatch, 1, {"steps": 3, "failed": 1},
                         ["residue recorded by the teardown: bracket-fault"])
    assert R.measure(row)["verdict"] == "fault-test"


def _fake_outcome(row, drifting):
    if row["expected"] == "compile" and not drifting:
        return {"verdict": "compile", "refusal": row.get("refusal", "checker"),
                "code": row["expectedCode"], "line": 1, "detail": "stub"}
    verdict = "missed" if drifting else row["expected"]
    return {"verdict": verdict, "detail": "stub", "counts": {"steps": 1}}


def _write_run(monkeypatch, tmp_path, drifting):
    results = tmp_path / "bench" / "results" / "saga-defect-corpus.md"
    monkeypatch.setattr(R, "ROOT", tmp_path)
    monkeypatch.setattr(R, "RESULTS", results)
    fake = lambda row, *_args, **_kwargs: _fake_outcome(row, drifting)  # noqa: E731
    monkeypatch.setattr(R, "measure", fake)
    monkeypatch.setattr(R, "measure_bounded", fake, raising=False)
    return R.main(["--write"]), results


def test_write_leaves_the_results_alone_when_a_row_drifts(monkeypatch, tmp_path):
    code, results = _write_run(monkeypatch, tmp_path, drifting=True)
    assert code == 1
    assert not results.exists(), "a drifting run replaced the pinned results"


def test_write_refreshes_the_results_when_no_row_drifts(monkeypatch, tmp_path):
    # control: the guard must not stop an agreeing run from writing
    code, results = _write_run(monkeypatch, tmp_path, drifting=False)
    assert code == 0
    assert results.is_file()


def test_a_hung_row_times_out_and_is_named(monkeypatch, capsys):
    row = COMPILE_ROWS[0]
    monkeypatch.setattr(R, "_row_command", lambda _row: [
        sys.executable, "-c", "import time; time.sleep(30)"], raising=False)
    started = time.monotonic()
    code = R.main(["--only", row["id"], "--timeout", "0.5"])
    elapsed = time.monotonic() - started
    assert code == 1
    assert f"{row['id']}: timed out after 0.5s" in capsys.readouterr().err
    assert elapsed < 5, f"the bound did not stop the row ({elapsed:.1f}s)"


def test_a_bounded_row_measures_what_the_in_process_row_measures():
    # control for the child process: a compile row needs no cordis-py
    row = COMPILE_ROWS[0]
    assert R.measure_bounded(row, timeout=120) == R.measure(row)


# ------------------------------------------------------------- measurement

@pytest.mark.slow
@pytest.mark.skipif(
    not HAS_CORDIS,
    reason="the fault sweep needs the pinned cordis-py runtime; the full gate "
           "installs it through backends/python/setup.sh")
def test_the_committed_table_is_the_measured_table():
    outcomes = {row["id"]: R.measure(row) for row in ROWS}
    drift = []
    for row in ROWS:
        problems = R.disagreements(row, outcomes[row["id"]])
        if problems:
            drift.append(f"{row['id']}: " + "; ".join(problems))
    assert not drift, "\n".join(drift)

    committed = _committed_verdicts()
    stale = [row["id"] for row in ROWS
             if committed.get(row["id"]) != outcomes[row["id"]]["verdict"]]
    assert not stale, (
        "bench/results/saga-defect-corpus.md is stale for "
        f"{stale}; rerun `python3 bench/saga_defects/run.py --write`")

    totals = R.tally(ROWS, outcomes)
    measured = {"rows": totals["rows"], "compile": totals["compile"],
                "checker": totals["checker"], "parse": totals["parse"],
                "checker_kinds": totals["checker_kinds"],
                "fault_test": totals["fault-test"], "missed": totals["missed"]}
    assert _committed_totals() == measured, (
        "the committed totals disagree with the measurement")
