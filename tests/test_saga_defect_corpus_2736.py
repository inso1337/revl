def test_the_slice_has_between_12_and_20_defects():
    assert 12 <= len(ROWS) <= 20, (
        "the first slice of issue #2736 asks for 12 to 20 seeded defects")


def test_every_row_has_its_own_saga():
    files = [row["file"] for row in ROWS]
    assert len(files) == len(set(files)), "one defect per saga file"


def test_the_rows_cover_the_defect_classes_the_issue_names():
    kinds = {row["kind"] for row in ROWS}
    assert {"missing-undo", "unmarked-emission", "dependency-cycle",
            "manual-teardown", "failing-inverse", "failing-compensation",
            "missing-compensate", "wrong-inverse-target"} <= kinds


def test_every_compile_row_records_its_refusal_code():
    for row in COMPILE_ROWS:
        assert row.get("expectedCode"), (
            f"{row['id']}: a compile row must record the expected refusal code")


def test_rows_sharing_a_kind_under_one_verdict_say_so():
    # Two rows of one defect kind under one catch point are one defect kind at
    # two sites; each such row must say so in its description, so a count of
    # rows is not read as a count of distinct defects.
    seen = {}
    for row in ROWS:
        seen.setdefault((row["expected"], row.get("refusal"), row["kind"]), []).append(row)
    for same in seen.values():
        if len(same) < 2:
            continue
        for row in same:
            others = [other["id"] for other in same if other is not row]
            assert "one defect kind" in row["description"], row["id"]
            assert all(f"`{other}`" in row["description"] for other in others), row["id"]


@pytest.mark.parametrize("row", COMPILE_ROWS, ids=[row["id"] for row in COMPILE_ROWS])
def test_each_compile_row_is_refused_with_its_code(row):
    _ir, refusal = R._compile(BENCH / row["file"])
    assert refusal is not None, (
        f"{row['id']}: expected a compile refusal, but the saga compiled")
    assert _code(refusal) == row["expectedCode"], (
        f"{row['id']}: got {_code(refusal)!r}, want {row['expectedCode']!r}: "
        f"{refusal.message}")
    assert R.refusal_kind(refusal) == row.get("refusal", "checker"), (
        f"{row['id']}: the refusal is a {R.refusal_kind(refusal)} refusal, the "
        f"row says {row.get('refusal', 'checker')}: {refusal.message}")


def test_a_generic_parse_error_is_a_parse_refusal_and_a_named_rule_is_not():
    # Controls for `refusal_kind`: a plain typo is a parse refusal, and the
    # parser-raised G4 missing-undo refusal is still a checker refusal.
    from revl.errors import RevlError

    typo = BENCH / "sagas" / "missing_undo_hold.rvl"
    text = typo.read_text(encoding="utf-8").replace("service Inventory {", "servce Inventory {")
    try:
        importlib.import_module("revl.parser").parse_text(text, str(typo))
    except RevlError as error:
        assert R.refusal_kind(error) == "parse", error.message
    else:
        raise AssertionError("the typo parsed")
    _ir, refusal = R._compile(typo)
    assert refusal is not None and R.refusal_kind(refusal) == "checker"


@pytest.mark.parametrize("row", RUNTIME_ROWS, ids=[row["id"] for row in RUNTIME_ROWS])
def test_each_runtime_row_compiles_cleanly(row):
    ir, refusal = R._compile(BENCH / row["file"])
    assert refusal is None, (
        f"{row['id']}: a runtime verdict needs a compiling saga, got "
        f"{refusal.code}: {refusal.message}")
    names = {component.get("name") for component in ir["components"]}
    assert row["component"] in names


def test_the_results_table_covers_every_row():
    assert set(_committed_verdicts()) == {row["id"] for row in ROWS}


# The paper sentences that quote the corpus totals. A measured number in prose
# is a claim that can drift, so each is pinned to the committed measurement by
# line, as phrases: each phrase is the number together with its label, written
# with the `_committed_totals` key in braces, and must appear on the line as a
# whole with no digit directly before it. A number found elsewhere on the line,
# or under another label, does not satisfy a phrase. A line move or a wording
# edit that keeps the numbers is a test change, not a paper change; that is
# deliberate, because the pins are what make the prose checkable at all.
PAPER_TOTALS = {
    "docs/research/papers/P01-typed-revertible-effects.md": {
        7: ("{rows} sagas",),
        17: ("{rows} small sagas", "{compile} defects are refused at compile time",
             "({checker} by a checker rule", "covering {checker_kinds} defect kinds",
             "{parse} by a parse error",
             "{fault_test} are caught only by the generated fault sweep",
             "{missed} are missed by both"),
        68: ("{rows} rows: {compile} refused at compile",
             "({checker} by a checker rule over {checker_kinds} defect kinds",
             "{parse} by a parse error)", "{fault_test} caught only by the fault sweep",
             "{missed} missed by both"),
        75: ("{rows} rows, one seeded saga defect each",
             "{compile} are refused at compile time", "{checker} by a checker rule",
             "covering {checker_kinds} defect kinds", "{parse} (`emission-with-undo`) by a "
             "parse error", "{fault_test} are caught only by the `revl test --sweep` "
             "fault sweep", "{missed} are missed by both"),
        76: ("on those {rows} seeded rows",),
        87: ("({rows} rows scored",),
        97: ("each of {rows} seeded rows is caught",),
        98: ("The {missed} missed rows",),
    },
    "docs/research/papers/P16-testing-recovery-claims-sweep-roundtrip.md": {
        7: ("{fault_test} of {rows} seeded rows are caught only by the sweep",
            "{missed} are missed", "{compile} are refused at compile",
            "({checker} by a checker rule", "{parse} by a parse error"),
        73: ("{rows} rows (", "{compile} refused at compile",
             "({checker} by a checker rule", "{parse} by a parse error)",
             "{fault_test} caught only by the sweep", "{missed} missed by both"),
    },
}


def _paper_drift(texts, measured):
    """Every pinned phrase that the paper texts do not state, as messages."""
    drift = []
    for relative, pinned in PAPER_TOTALS.items():
        lines = texts[relative].splitlines()
        for line_no, phrases in pinned.items():
            if line_no > len(lines):
                drift.append(f"{relative}:{line_no} is past the end of the paper")
                continue
            line = lines[line_no - 1]
            for template in phrases:
                phrase = template.format(**measured)
                if re.search(r"(?<!\d)" + re.escape(phrase), line) is None:
                    drift.append(f"{relative}:{line_no} does not state {phrase!r}")
    return drift


def _paper_texts():
    return {relative: (ROOT / relative).read_text(encoding="utf-8")
            for relative in PAPER_TOTALS}


def test_every_paper_pin_states_a_number():
    for pinned in PAPER_TOTALS.values():
        for phrases in pinned.values():
            for template in phrases:
                assert re.search(r"\{(\w+)\}", template), template
                assert set(re.findall(r"\{(\w+)\}", template)) <= set(TOTAL_KEYS)


def test_every_total_is_pinned_in_some_paper_line():
    used = {key for pinned in PAPER_TOTALS.values() for phrases in pinned.values()
            for template in phrases for key in re.findall(r"\{(\w+)\}", template)}
    assert used == set(TOTAL_KEYS)


def test_the_paper_totals_are_the_measured_totals():
    drift = _paper_drift(_paper_texts(), _committed_totals())
    assert not drift, "\n".join(drift)


