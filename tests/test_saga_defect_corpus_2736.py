"""The seeded-defect saga corpus (issue #2736): bench/saga_defects/.

The static half of the exit runs everywhere: the data file is the index, every
row names a saga that exists, every row that expects a compile refusal is
refused with the recorded code, and every row that expects a runtime verdict
compiles (so its classification is meaningful rather than a compile refusal in
disguise).

The measurement half is `run.py` itself and is slow by nature: it compiles and
fault-sweeps 16 sagas on the real runtime. It is marked `slow` and needs the
pinned cordis-py, which the full gate installs through
`backends/python/setup.sh`; the fast lanes deselect it. It checks the measured
verdicts against the committed table, so the table cannot silently go stale.
"""

import importlib
import importlib.util
import re
import sys
import time
import types
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
BENCH = ROOT / "bench" / "saga_defects"
RESULTS = ROOT / "bench" / "results" / "saga-defect-corpus.md"
HAS_CORDIS = importlib.util.find_spec("cordis") is not None


def _load():
    spec = importlib.util.spec_from_file_location("saga_defects_bench", BENCH / "run.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


R = _load()
DATA = R.load_corpus()
ROWS = DATA["defects"]
COMPILE_ROWS = [row for row in ROWS if row["expected"] == "compile"]
RUNTIME_ROWS = [row for row in ROWS if row["expected"] != "compile"]


def _code(error):
    if error.code is not None:
        return error.code
    return importlib.import_module("revl.diagnostics").classify(error)["code"]


def _committed_verdicts():
    text = RESULTS.read_text(encoding="utf-8")
    verdicts = {}
    for line in text.splitlines():
        if not line.startswith("| `"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) != 6:
            continue
        verdicts[cells[0].strip("`")] = cells[4].strip("*")
    return verdicts


TOTAL_KEYS = ("rows", "compile", "checker", "parse", "checker_kinds",
              "fault_test", "missed")


def _committed_totals(text=None):
    """The totals the committed results file states, by the names the paper
    templates use. The counts come from the bold summary line and the defect
    kinds from the catch-point table; both are generated by `run.py --write`.
    """
    text = RESULTS.read_text(encoding="utf-8") if text is None else text
    summary = re.search(
        r"\*\*(\d+) rows: (\d+) refused at compile \((\d+) by a checker rule, "
        r"(\d+) by a parse error\), (\d+) caught by a fault test, (\d+) missed "
        r"by both", text)
    assert summary is not None, "the results table lost its totals line"
    kinds = re.search(
        r"^\| refused at compile by a checker rule \| (\d+) \| (\d+) \|$", text,
        re.MULTILINE)
    assert kinds is not None, "the results table lost its catch-point table"
    rows, compile_, checker, parse, fault_test, missed = (
        int(part) for part in summary.groups())
    assert int(kinds.group(1)) == checker, "the summary and the table disagree"
    return {"rows": rows, "compile": compile_, "checker": checker,
            "parse": parse, "checker_kinds": int(kinds.group(2)),
            "fault_test": fault_test, "missed": missed}


