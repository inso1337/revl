    fn no_runtime_configured_resolves_to_nothing() {
        // With no runtime env set, `locate` may only answer from a runtime
        // bundled beside the test binary, which a `cargo` build never has — so
        // the PATH fallback stands and slice-1 behavior is unchanged.
        for var in [RUNTIME_DIR_ENV, RUNTIME_ARCHIVE_ENV] {
            assert!(
                std::env::var_os(var).is_none(),
                "{var} leaked into the unit-test environment"
            );
        }
        // A bare `cargo` build bakes no runtime, so the embedded source is `None`
        // too and `locate` truly resolves nothing.
        assert!(
            EMBEDDED_RUNTIME.is_none(),
            "the test binary was built with REVL_LSP_EMBED_RUNTIME set"
        );
        assert!(locate().is_none());
    }

    #[test]
    fn embedded_bytes_extract_into_a_versioned_cache_and_reuse_it() {
        // The single-distributed-file path: bytes that would be baked into the
        // binary extract through the same atomic, versioned-cache path an archive
        // BESIDE the binary takes. This drives it with an explicit destination, so
        // it touches no process env and races no other unit test.
        let scratch = std::env::temp_dir().join(format!(
            "revl-lsp-embed-unit-{}-{}",
            std::process::id(),
            nonce()
        ));
        let runtime = scratch.join("runtime");
        std::fs::create_dir_all(runtime.join("bin")).unwrap();
        let launcher = runtime.join("bin").join("python3");
        std::fs::write(&launcher, b"#!/bin/sh\nexit 0\n").unwrap();

        let archive = scratch.join("runtime.tar");
        let built = Command::new("tar")
            .arg("-cf")
            .arg(&archive)
            .arg("-C")
            .arg(&runtime)
            .arg(".")
            .status()
            .map(|status| status.success())
            .unwrap_or(false);
        if !built {
            eprintln!("SKIPPED: `tar` is unavailable to build the runtime archive");
            let _ = std::fs::remove_dir_all(&scratch);
            return;
        }
        let bytes = std::fs::read(&archive).unwrap();

        let dest = scratch
            .join("cache")
            .join("revl-lsp")
            .join("runtime")
            .join("embed-unit-pin");

        // First: the bytes extract atomically into the versioned dest, isolated.
        let first =
            ensure_extracted_bytes_into(&bytes, &dest).expect("embedded bytes should extract");
        assert!(first.isolated, "an embedded runtime must launch in isolated mode");
        // Baked-in bytes report the single-distributed-FILE shape and the pin
        // they cached under, which is what a distribution audit reads.
        assert_eq!(first.source, Source::Embedded);
        assert_eq!(first.pin, "embed-unit-pin");
        assert!(
            dest.join("bin").join("python3").is_file(),
            "the interpreter did not land in the versioned cache at {}",
            dest.display()
        );
        assert!(Path::new(&first.python).ends_with("bin/python3"));

        // Second: the populated cache is REUSED, not re-extracted — a sentinel a
        // re-extract would erase survives.
        let sentinel = dest.join("REUSED_MARKER");
        std::fs::write(&sentinel, b"kept").unwrap();
        let second =
            ensure_extracted_bytes_into(&bytes, &dest).expect("the cache should be reused");
        assert_eq!(first.python, second.python);
        assert_eq!(second.source, Source::Embedded, "the reuse path keeps the shape");
        assert_eq!(second.pin, "embed-unit-pin");
        assert!(
            sentinel.is_file(),
            "the second call re-extracted the runtime instead of reusing the cache"
        );

        let _ = std::fs::remove_dir_all(&scratch);
    }

